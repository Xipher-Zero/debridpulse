def by_provider(status):
    return {item["provider_id"]: item for item in status["providers"]}


async def test_a_provider_serving_only_an_equivalent_source_is_offered_and_becomes_primary(tmp_path, monkeypatch):
    """One file on ddownload via prov-rd, with equivalent 1fichier (prov-ad)
    and pixeldrain (prov-tb) sources. prov-tb cannot serve ddownload, yet it
    is offered and choosing it moves the file onto its pixeldrain source --
    no host switch first -- with one writer; prov-ad stays offered for its
    claim, prov-x (no claim on any source) is not offered."""
    from application.manual_route_switch import switch_transfer_provider
    from test_v113_root_provider_switch import application_of
    from transfers.manual_route_switch import transfer_route_status
    lab_ = await primary_lab(tmp_path, monkeypatch, (DDL1, FICHIER01, PIX1))
    part = await file_of(lab_.repository, lab_.transfer.id, "part01.rar")
    assert part.state == "downloading" and part.candidates[part.selected].provider_id == "prov-rd"
    first = part.execution.attempt_id
    assert (await listed(lab_))["route_switch_scope"] == "transfer"

    status = await transfer_route_status(lab_.engine, lab_.transfer.id)
    offered = by_provider(status)
    assert set(offered) == {"prov-rd", "prov-ad", "prov-tb"}
    assert offered["prov-rd"]["already_selected"] == 1
    for provider in ("prov-tb", "prov-ad"):
        (row,) = offered[provider]["roots"]
        assert offered[provider]["selectable"] and row["status"] == "eligible" and row["via"] == "source"
    roots = await roots_by_link(lab_.repository, lab_.transfer.id)
    assert offered["prov-tb"]["roots"][0]["plan"][0]["via_root_id"] == roots[PIX1]

    result = await switch_transfer_provider(application_of(lab_.engine), lab_.transfer.id, "prov-tb",
                                            expected_routes={roots[DDL1]: "prov-rd"})
    assert (result["result"], result["switched"]) == ("complete", 1)
    assert [item["outcome"] for item in result["roots"][0]["files"]] == ["switched"]
    await settle(lab_.engine, 6)
    part = await file_of(lab_.repository, lab_.transfer.id, "part01.rar")
    assert part.state == "downloading", part.error
    assert part.candidates[part.selected].provider_id == "prov-tb"
    assert part.candidates[part.selected].source_identity.key == "pixeldrain.com"
    assert running(lab_) == [part.execution.attempt_id] and part.execution.attempt_id != first
    assert set(lab_.issuer.refreshed) == {PIX_MEMBER}
    item = await listed(lab_)
    assert item["active_provider_id"] == "prov-tb" and item["route_switch_scope"] == "transfer"
    # Another provider stays a choice from there (repeatable): prov-rd and prov-ad.
    assert {"prov-rd", "prov-ad"} <= {key for key, value in by_provider(
        await transfer_route_status(lab_.engine, lab_.transfer.id)).items() if value["selectable"]}


