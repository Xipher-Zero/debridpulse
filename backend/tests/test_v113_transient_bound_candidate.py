async def test_a_provider_claiming_an_equivalent_link_it_cannot_take_now_is_listed_with_its_restriction(
        tmp_path, monkeypatch):
    """Availability never narrows the choices: prov-y legitimately claims the
    equivalent pixeldrain link but declined it for this transfer. It is
    listed, not selectable, and its row says why (``declined``) -- not
    "cannot use this link"; prov-x, claiming no source, stays absent."""
    from db.database import get_db
    from transfers.manual_route_switch import transfer_route_status
    lab_ = await alternate_lab(tmp_path, monkeypatch)
    roots = await roots_by_link(lab_.repository, lab_.transfer.id)
    async with get_db() as db:
        await db.execute("INSERT INTO resolution_attempts(id,request_id,provider_id,state) VALUES(?,?,?,'declined')",
                         ("declined-y", roots[PIX1], "prov-y"))
        await db.commit()
    status = by_provider(await transfer_route_status(lab_.engine, lab_.transfer.id))
    assert "prov-y" in status and not status["prov-y"]["selectable"]
    (row,) = status["prov-y"]["roots"]
    assert (row["status"], row["reason"]) == ("unavailable", "declined")
    assert "prov-x" not in status
