class ClaimingProvider:
    """A neutral direct-link provider claiming exactly ``hosts``."""

    def __init__(self, identity, hosts, priority=1):
        self.descriptor = IntegrationDescriptor(identity, identity, frozenset({Capability.RESOLVE}),
                                                request_types=frozenset({"https"}), priority=priority)
        self.failures: list = []                      # errors raised by the next resolutions, in order
        self.resolved: list[str] = []
        self.applicability = ProviderApplicability(
            specialized_hosts=tuple(HostClaim(host, HostClaimScope.DOMAIN, frozenset({"https"})) for host in hosts),
            specialized=True, readiness=ApplicabilityReadiness.READY)

    async def resolve(self, request):
        self.resolved.append(str(request.payload))
        if self.failures:
            raise TransferError(self.failures.pop(0))
        name = str(request.payload).rsplit("/", 1)[-1]
        return ResolutionResult(ResourceState.AVAILABLE, (TransferCandidate(
            name, (Endpoint("memory", f"memory:{name}"),), expected_bytes=4, provider_id=self.descriptor.id),))


