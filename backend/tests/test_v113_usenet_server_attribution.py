"""DP 1.0.13: which Usenet servers actually delivered a transfer.

Source of truth (bundled SABnzbd 5.1.3, read in the packaged image):

* ``newswrapper.on_response`` counts a server's bytes for a job ONLY on a
  220/222 response -- one whole article fetched from that server; missing
  article answers (430...) are never counted (``nzb.update_download_stats``,
  per job ``servercount`` keyed by the server's keyword).
* When the job leaves the queue (``nzbqueue.py`` ``set_download_report``)
  the counts become the history ``stage_log`` stage ``Servers``:
  ``"<displayname>=<to_units(bytes)>B"`` per server that delivered, ", "
  joined, rounded to binary units -- the only per-job form any API exposes.

DebridPulse's keyword for a server is ``dp-<canonical id>``; the report names
it by display name, so the executor attributes a line through the service's
own current ``(keyword, displayname)`` map, and only when exactly one managed
server carries that name. Recorded once per execution attempt
(``execution_attempts.contributors``), never erased, kept after the service
forgets the job, shown in Details beneath Provider, exported in the trace.

Fixtures: ``fixtures/sab_server_report/stage_logs.json``, generated by
``gen.py`` with SABnzbd 5.1.3's own ``to_units`` and history unpacking.
"""
