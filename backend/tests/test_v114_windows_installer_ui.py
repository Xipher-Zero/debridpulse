"""The Windows installer's interface: Modern UI 2, drawn at the display's own
scale, in DownloadPulse's own pictures, with Launch on its Finish page.

The pictures are generated by the build (packaging/desktop/assemble.py
installer_bitmaps) into the icons the installer is assembled with; the Finish
page starts the same command as the Start-menu shortcut, after the installer
has let go of the data root's lock.
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
NSI = (ROOT / "packaging" / "desktop" / "windows" / "installer.nsi").read_text(encoding="utf-8")
ASSEMBLE = (ROOT / "packaging" / "desktop" / "assemble.py").read_text(encoding="utf-8")


def test_the_installer_is_modern_ui_2_drawn_at_the_displays_scale():
    assert '!include "MUI2.nsh"' in NSI
    for line in ("ManifestDPIAware true", "XPStyle on", 'BrandingText "DownloadPulse ${VERSION}"'):
        assert line in NSI, line
    pages = re.findall(r"!insertmacro (MUI_(?:UN)?PAGE_\w+)", NSI)
    assert pages == ["MUI_PAGE_WELCOME", "MUI_PAGE_LICENSE", "MUI_PAGE_DIRECTORY", "MUI_PAGE_INSTFILES",
                     "MUI_PAGE_FINISH", "MUI_UNPAGE_CONFIRM", "MUI_UNPAGE_INSTFILES", "MUI_UNPAGE_FINISH"]
    assert not re.search(r"^\s*(Un[Ii]nst)?Page\s", NSI, re.M)          # no classic page left
    assert "LicenseData" not in NSI


def test_its_pictures_are_the_ones_the_build_generates():
    for name in ("installer-side.bmp", "installer-header.bmp"):
        assert f'"${{DP_ICONS}}\\{name}"' in NSI, name
        assert f"out / '{name}'" in ASSEMBLE
    assert "installer_bitmaps(magick, out, static)" in ASSEMBLE
    assert "INSTALLER_SIDE, INSTALLER_HEADER = (328, 628), (300, 114)" in ASSEMBLE   # twice 164 x 314 and 150 x 57
    assert "BMP3:" in ASSEMBLE


def test_launch_on_the_finish_page_is_the_shortcuts_command_after_the_lock_is_released():
    launch = re.search(r"Function LaunchDownloadPulse\n(.*?)FunctionEnd", NSI, re.S).group(1)
    shortcut = re.search(r'CreateShortcut "\$SMPROGRAMS\\DownloadPulse\.lnk" "([^"]+)" \'([^\']+)\'', NSI)
    assert f'Exec \'"{shortcut.group(1)}" {shortcut.group(2)}\'' in launch
    assert "!define MUI_FINISHPAGE_RUN_FUNCTION LaunchDownloadPulse" in NSI
    released = re.search(r"Function \.onInstSuccess\n(.*?)FunctionEnd", NSI, re.S).group(1)
    assert "Call ReleaseDataRootLock" in released
